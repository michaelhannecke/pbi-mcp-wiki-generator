"""
Wiki page generators for Power BI documentation.

This module contains functions to generate individual wiki pages
from Power BI model metadata.
"""
from datetime import datetime, timezone
from typing import Any
import re

from ..mcp_client.pbixray_tools import (
    Table, Measure, Relationship, CalculatedColumn, ModelSummary
)


def slugify(text: str) -> str:
    """Convert text to URL-safe slug."""
    slug = text.lower()
    slug = re.sub(r'[^\w\s-]', '', slug)
    slug = re.sub(r'[\s_]+', '-', slug)
    return slug.strip('-')


def escape_markdown(text: str) -> str:
    """Escape special Markdown characters."""
    if not text:
        return ""
    chars = ['|', '`', '*', '_', '[', ']', '<', '>']
    for char in chars:
        text = text.replace(char, f'\\{char}')
    return text


def format_dax(expression: str) -> str:
    """Format DAX expression for display."""
    if not expression:
        return ""
    # Basic formatting - could be enhanced with proper DAX parser
    return expression.strip()


def generate_home_page(
    model_name: str,
    summary: ModelSummary,
    tables: list[Table],
    measures: list[Measure],
    generated_at: datetime | None = None
) -> str:
    """
    Generate the wiki home page.
    
    Args:
        model_name: Name of the Power BI model
        summary: Model summary statistics
        tables: List of tables in the model
        measures: List of measures in the model
        generated_at: Timestamp for generation (default: now)
        
    Returns:
        Markdown content for home page
    """
    if generated_at is None:
        generated_at = datetime.now(timezone.utc)
    
    timestamp = generated_at.strftime("%Y-%m-%d %H:%M UTC")
    
    # Build table navigation
    table_links = []
    for t in sorted(tables, key=lambda x: x.name):
        if not t.is_hidden:
            table_links.append(f"- [{t.name}](Table-{slugify(t.name)})")
    
    tables_section = "\n".join(table_links) if table_links else "_No visible tables_"
    
    # Count visible measures
    visible_measures = [m for m in measures if not m.is_hidden]
    
    content = f"""# {model_name}

## Semantic Model Documentation

> 📅 Auto-generated on **{timestamp}**

---

## Model Overview

| Metric | Count |
|:-------|------:|
| Tables | {summary.table_count} |
| Columns | {summary.column_count} |
| Measures | {len(visible_measures)} |
| Relationships | {summary.relationship_count} |
"""

    if summary.size_bytes:
        size_mb = summary.size_bytes / (1024 * 1024)
        content += f"| Model Size | {size_mb:.2f} MB |\n"
    
    content += f"""
---

## Quick Navigation

### 📊 Tables

{tables_section}

### 📐 Analysis

- [All Measures](Measures) — Complete DAX measure reference
- [Relationships](Relationships) — Model relationships with ER diagram
- [Data Sources](Data-Sources) — Power Query/M code documentation

---

## About This Documentation

This wiki is automatically generated from the Power BI model file.
**Do not edit manually** — changes will be overwritten on the next generation.

### Refresh Cycle

Documentation regenerates automatically when:
- The PBIX file is updated in the repository
- The documentation workflow is manually triggered

### Feedback

If you find issues with the documentation, please:
1. Check if the underlying model has the correct metadata
2. Open an issue in the repository if the generator needs fixes

---

*Generated by [pbi-wiki-generator](https://github.com/your-org/pbi-wiki-generator)*
"""
    
    return content


def generate_table_page(
    table: Table,
    schema: dict[str, Any],
    measures: list[Measure],
    calculated_columns: list[CalculatedColumn] | None = None,
    power_query: str | None = None
) -> str:
    """
    Generate documentation page for a single table.
    
    Args:
        table: Table object
        schema: Schema dictionary with column details
        measures: All measures (filtered to this table)
        calculated_columns: Calculated columns for this table
        power_query: Power Query/M expression for this table
        
    Returns:
        Markdown content for table page
    """
    content = f"# {table.name}\n\n"
    
    if table.description:
        content += f"_{table.description}_\n\n"
    
    if table.row_count is not None:
        content += f"**Row Count:** {table.row_count:,}\n\n"
    
    # Columns section
    content += "## Columns\n\n"
    content += "| Column | Data Type | Description |\n"
    content += "|:-------|:----------|:------------|\n"
    
    columns = schema.get("columns", [])
    if not columns and table.columns:
        columns = [{"name": c.name, "data_type": c.data_type, "description": c.description} 
                   for c in table.columns]
    
    for col in columns:
        name = escape_markdown(col.get("name", ""))
        data_type = col.get("data_type", col.get("dataType", "Unknown"))
        desc = escape_markdown(col.get("description", ""))
        content += f"| {name} | `{data_type}` | {desc} |\n"
    
    # Calculated columns
    if calculated_columns:
        table_calc_cols = [c for c in calculated_columns if c.table == table.name]
        if table_calc_cols:
            content += "\n## Calculated Columns\n\n"
            for calc_col in table_calc_cols:
                content += f"### {calc_col.name}\n\n"
                content += f"```dax\n{format_dax(calc_col.expression)}\n```\n\n"
                if calc_col.description:
                    content += f"_{calc_col.description}_\n\n"
    
    # Measures section
    table_measures = [m for m in measures if m.table == table.name and not m.is_hidden]
    if table_measures:
        content += "\n## Measures\n\n"
        for measure in sorted(table_measures, key=lambda m: m.name):
            content += f"### {measure.name}\n\n"
            content += f"```dax\n{format_dax(measure.expression)}\n```\n\n"
            if measure.format_string:
                content += f"**Format:** `{measure.format_string}`\n\n"
            if measure.description:
                content += f"_{measure.description}_\n\n"
    
    # Power Query section
    if power_query:
        content += "\n## Power Query Source\n\n"
        content += f"```powerquery\n{power_query}\n```\n\n"
    
    content += "\n---\n\n[← Back to Home](Home)\n"
    
    return content


def generate_measures_page(
    measures: list[Measure],
    include_hidden: bool = False
) -> str:
    """
    Generate consolidated measures documentation page.
    
    Args:
        measures: All measures in the model
        include_hidden: Whether to include hidden measures
        
    Returns:
        Markdown content for measures page
    """
    if not include_hidden:
        measures = [m for m in measures if not m.is_hidden]
    
    # Group by table
    by_table: dict[str, list[Measure]] = {}
    for m in measures:
        by_table.setdefault(m.table, []).append(m)
    
    content = "# DAX Measures Reference\n\n"
    content += f"*Total measures: {len(measures)}*\n\n"
    
    # Table of contents
    content += "## Contents\n\n"
    for table_name in sorted(by_table.keys()):
        count = len(by_table[table_name])
        content += f"- [{table_name}](#{slugify(table_name)}) ({count} measures)\n"

    content += "\n---\n\n"

    # Measure details by table
    for table_name in sorted(by_table.keys()):
        # Use explicit anchor to ensure TOC links work correctly
        content += f'<a id="{slugify(table_name)}"></a>\n\n'
        content += f"## {table_name}\n\n"
        
        for measure in sorted(by_table[table_name], key=lambda m: m.name):
            content += f"### {measure.name}\n\n"
            content += f"```dax\n{format_dax(measure.expression)}\n```\n\n"
            
            # Metadata table
            meta_rows = []
            if measure.format_string:
                meta_rows.append(f"| Format | `{measure.format_string}` |")
            if measure.display_folder:
                meta_rows.append(f"| Folder | {measure.display_folder} |")
            if measure.description:
                meta_rows.append(f"| Description | {escape_markdown(measure.description)} |")
            
            if meta_rows:
                content += "| Property | Value |\n|:---------|:------|\n"
                content += "\n".join(meta_rows) + "\n\n"
    
    content += "\n---\n\n[← Back to Home](Home)\n"
    
    return content


def generate_relationships_page(
    relationships: list[Relationship],
    er_diagram: str,
    data_flow_diagram: str | None = None
) -> str:
    """
    Generate relationships documentation with diagrams.
    
    Args:
        relationships: List of model relationships
        er_diagram: Mermaid ER diagram code
        data_flow_diagram: Optional data flow diagram
        
    Returns:
        Markdown content for relationships page
    """
    content = "# Model Relationships\n\n"
    content += f"*Total relationships: {len(relationships)}*\n\n"
    
    # ER Diagram
    content += "## Entity Relationship Diagram\n\n"
    content += f"```mermaid\n{er_diagram}\n```\n\n"
    
    # Data flow diagram if provided
    if data_flow_diagram:
        content += "## Data Flow\n\n"
        content += "This diagram shows how data flows from dimension tables to fact tables.\n\n"
        content += f"```mermaid\n{data_flow_diagram}\n```\n\n"
        content += """
**Legend:**
- 🔵 Blue boxes: Dimension tables
- 🟠 Orange boxes: Fact tables  
- 🟣 Purple boxes: Bridge/junction tables
- Solid arrows: Active relationships
- Dashed arrows: Inactive relationships

"""
    
    # Relationship details table
    content += "## Relationship Details\n\n"
    content += "| From Table | From Column | → | To Table | To Column | Active | Direction |\n"
    content += "|:-----------|:------------|:-:|:---------|:----------|:------:|:----------|\n"
    
    for r in sorted(relationships, key=lambda x: (x.from_table, x.from_column)):
        active_icon = "✅" if r.is_active else "⬜"
        direction = r.cross_filter_direction
        content += (
            f"| {r.from_table} | {r.from_column} | → | "
            f"{r.to_table} | {r.to_column} | {active_icon} | {direction} |\n"
        )
    
    # Inactive relationships callout
    inactive = [r for r in relationships if not r.is_active]
    if inactive:
        content += "\n### ⚠️ Inactive Relationships\n\n"
        content += "The following relationships are inactive and must be explicitly activated using `USERELATIONSHIP()`:\n\n"
        for r in inactive:
            content += f"- `{r.from_table}[{r.from_column}]` → `{r.to_table}[{r.to_column}]`\n"
    
    content += "\n---\n\n[← Back to Home](Home)\n"
    
    return content


def generate_data_sources_page(
    power_query: dict[str, str],
    tables: list[Table]
) -> str:
    """
    Generate data sources documentation from Power Query code.
    
    Args:
        power_query: Dictionary mapping table names to M expressions
        tables: List of tables for additional context
        
    Returns:
        Markdown content for data sources page
    """
    content = "# Data Sources\n\n"
    content += "This page documents the Power Query/M expressions used to load and transform data.\n\n"
    
    if not power_query:
        content += "_No Power Query expressions found in this model._\n\n"
        content += "This may indicate:\n"
        content += "- The model uses DirectQuery or Live Connection\n"
        content += "- Data was imported via other means\n"
        content += "- The PBIX file format doesn't expose M code\n\n"
    else:
        # Group queries by potential source type
        content += "## Queries\n\n"
        content += f"*Total queries: {len(power_query)}*\n\n"
        
        # Table of contents
        content += "### Quick Links\n\n"
        for query_name in sorted(power_query.keys()):
            content += f"- [{query_name}](#{slugify(query_name)})\n"
        
        content += "\n---\n\n"
        
        # Query details
        for query_name in sorted(power_query.keys()):
            query_code = power_query[query_name]
            
            content += f"## {query_name}\n\n"
            
            # Try to identify data source type
            source_hints = _identify_source_type(query_code)
            if source_hints:
                content += f"**Detected Source:** {source_hints}\n\n"
            
            content += f"```powerquery\n{query_code}\n```\n\n"
    
    content += "\n---\n\n[← Back to Home](Home)\n"
    
    return content


def generate_sidebar(tables: list[Table]) -> str:
    """
    Generate wiki sidebar navigation.
    
    Args:
        tables: List of tables for navigation
        
    Returns:
        Markdown content for sidebar
    """
    content = "**📊 Navigation**\n\n"
    content += "- [🏠 Home](Home)\n"
    content += "- [📐 Measures](Measures)\n"
    content += "- [🔗 Relationships](Relationships)\n"
    content += "- [💾 Data Sources](Data-Sources)\n\n"
    content += "**📋 Tables**\n\n"
    
    visible_tables = [t for t in tables if not t.is_hidden]
    for table in sorted(visible_tables, key=lambda t: t.name):
        content += f"- [{table.name}](Table-{slugify(table.name)})\n"
    
    return content


def _identify_source_type(m_code: str) -> str | None:
    """Attempt to identify the data source type from M code."""
    source_patterns = {
        "Sql.Database": "SQL Server",
        "Sql.Databases": "SQL Server",
        "Oracle.Database": "Oracle",
        "Odbc.Query": "ODBC",
        "OleDb.Query": "OLE DB",
        "Excel.Workbook": "Excel",
        "Csv.Document": "CSV File",
        "Json.Document": "JSON",
        "Web.Contents": "Web API",
        "SharePoint.Files": "SharePoint",
        "AzureStorage.Blobs": "Azure Blob Storage",
        "Snowflake.Databases": "Snowflake",
        "GoogleBigQuery.Database": "Google BigQuery",
        "Databricks.Catalogs": "Databricks",
        "Folder.Files": "Local Folder",
        "Table.FromRows": "Entered Data",
        "#table": "Entered Data",
    }
    
    detected = []
    for pattern, source_name in source_patterns.items():
        if pattern in m_code:
            detected.append(source_name)
    
    return ", ".join(detected) if detected else None
